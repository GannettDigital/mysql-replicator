import Foundation
import MySQLNIO
import ReplicatorCodec

/// A stored function has one outer statement boundary. This keeps ordered
/// MyISAM writes under one GTID, including keyless and repeated row identities.
/// Parameters retain their binary-protocol types in an unlogged scratch table.
struct MyISAMGTIDProgram {
    static let database = "`_mysql_replicator_gtid`"
    static let parameters = database+".`parameters`"
    static let function = database+".`apply_group`"
    static let owner = "mysql-replicator GTID scratch v1"
    var values: [(String,MySQLData)] = []

    mutating func expression(_ value:MySQLData) throws -> String {
        guard value.buffer != nil else { return "NULL" }
        let column:String
        switch value.type {
        case .longlong: column=value.isUnsigned ? "u" : "i"
        case .float: column="f"
        case .double: column="d"
        case .blob: column="b"
        case .date: column="dt"
        case .time: column="tm"
        case .datetime: column="ts"
        case .varString,.string: column="t"
        default: throw ApplyError("unsupported GTID scratch parameter type: \(value.type)")
        }
        values.append((column,value))
        return "(SELECT `\(column)` FROM \(Self.parameters) WHERE `id`=\(values.count))"
    }

    /// SQL is generated by our planner with NO_BACKSLASH_ESCAPES. Do not replace
    /// question marks inside quoted identifiers, literals or JSON path strings.
    mutating func expand(_ sql:String,_ binds:[MySQLData]) throws -> String {
        let bytes=Array(sql.utf8);var output=Data(),at=0,index=0,quote:UInt8?
        while at < bytes.count {
            let byte=bytes[at]
            if let q=quote {
                output.append(byte)
                if byte == q {
                    if at+1 < bytes.count,bytes[at+1] == q {at += 1;output.append(q)}
                    else {quote=nil}
                }
            } else if [39,34,96].contains(byte) {quote=byte;output.append(byte)}
            else if byte == 63 {
                try require(index < binds.count,"missing GTID scratch bind")
                output.append(contentsOf:try expression(binds[index]).utf8);index += 1
            } else {output.append(byte)}
            at += 1
        }
        try require(quote == nil && index == binds.count,"invalid GTID scratch SQL bindings")
        return String(decoding:output,as:UTF8.self)
    }
}

extension TargetSession {
    /// No scratch write is logged or used as a checkpoint. SQLite remains the
    /// only journal. The exclusive target writer lock protects these objects.
    func withoutScratchLogging<T>(_ body:() throws -> T) throws -> T {
        _ = try query("SET SESSION sql_log_bin=0",textProtocol:true)
        do {
            let value=try body()
            _ = try query("SET SESSION sql_log_bin=1",textProtocol:true)
            return value
        } catch {
            let original=error
            do {_ = try query("SET SESSION sql_log_bin=1",textProtocol:true)}
            catch {try? connection.close().wait();throw ApplyError("cannot restore target binary logging after GTID scratch preparation: \(original); \(error)")}
            throw original
        }
    }

    func preflightMyISAMGTIDSupport() throws {
        try withoutScratchLogging {
            try prepareGTIDScratch()
            _ = try query("CREATE FUNCTION \(MyISAMGTIDProgram.function)() RETURNS INT DETERMINISTIC SQL SECURITY INVOKER COMMENT '\(MyISAMGTIDProgram.owner)' RETURN 0",textProtocol:true)
            _ = try query("DROP FUNCTION \(MyISAMGTIDProgram.function)",textProtocol:true)
        }
    }
    private func prepareGTIDScratch() throws {
        let p=MyISAMGTIDProgram.parameters,db="_mysql_replicator_gtid",owner=MyISAMGTIDProgram.owner
        let existing=try scalar("SELECT TABLE_COMMENT AS v FROM information_schema.TABLES WHERE TABLE_SCHEMA=? AND TABLE_NAME='parameters'",[.init(string:db)])
        if let existing {try require(existing == owner,"reserved GTID scratch table belongs to another application")}
        else {
            try require(try scalar("SELECT COUNT(*) AS v FROM information_schema.SCHEMATA WHERE SCHEMA_NAME=?",[.init(string:db)]) == "0",
                "reserved GTID scratch database exists without its ownership marker")
            _ = try query("CREATE DATABASE \(MyISAMGTIDProgram.database)",textProtocol:true)
            _ = try query("CREATE TABLE \(p) (`id` BIGINT UNSIGNED PRIMARY KEY,`i` BIGINT,`u` BIGINT UNSIGNED,`f` FLOAT,`d` DOUBLE,`t` LONGTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin,`b` LONGBLOB,`dt` DATE,`tm` TIME(6),`ts` DATETIME(6)) ENGINE=MyISAM COMMENT='\(owner)'",textProtocol:true)
        }
        if let comment=try scalar("SELECT ROUTINE_COMMENT AS v FROM information_schema.ROUTINES WHERE ROUTINE_SCHEMA=? AND ROUTINE_NAME='apply_group'",[.init(string:db)]) {
            try require(comment == owner,"reserved GTID scratch function belongs to another application")
            _ = try query("DROP FUNCTION \(MyISAMGTIDProgram.function)",textProtocol:true)
        }
        _ = try query("TRUNCATE TABLE \(p)",textProtocol:true)
    }

    func applyMyISAMGTIDGroup(_ group:PreparedDMLGroup) throws {
        try unlock()
        var program=MyISAMGTIDProgram(),body=""
        var relaxed=false
        for mutation in group.mutations {
            let table=mutation.table,plan=try sqlPlan(table),row=mutation.row
            // Use exact full images inside the function, after earlier writes.
            // This retains the ordering required by keyless duplicates and PK changes.
            func predicate(_ image:[DecodedValue]) throws -> JSONSQLValue {
                let indexes=table.columns.indices.filter {!table.columns[$0].isGenerated}
                return try FullRowPredicate.make(table:table,types:plan.columnTypes,values:indexes.map {image[$0]},
                    compatibility:config.compatibilityPolicy,bind:bind,indexes:indexes)
            }
            if let before=row.before {
                let match=try predicate(before)
                body += "IF NOT EXISTS(SELECT 1 FROM \(try table.sqlName) WHERE \(try program.expand(match.sql,match.binds))) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='target before-image mismatch or missing row'; END IF;\n"
            }
            let expressions=try row.after.map { after in try plan.writeIndexes.map {try prepareJSONValue(after[$0],database:table.database)} } ?? []
            let writeSQL:String,binds:[MySQLData]
            if row.operation == "insert" {
                writeSQL=plan.insertSQL(expressions:[expressions.map(\.sql)])
                binds=expressions.flatMap(\.binds)
            } else {
                let before=row.before!,key=plan.keyIndexes.map {before[$0]}
                let lookup=try table.usesFullRowIdentity
                    ? FullRowPredicate.make(table:table,types:plan.columnTypes,values:key,compatibility:config.compatibilityPolicy,bind:bind)
                    : JSONSQLValue(sql:try plan.keyIndexes.map {try plan.columnTypes[$0].sqlKeyColumn(quoted(table.columns[$0].name))+"="+plan.columnTypes[$0].sqlValue("?")}.joined(separator:" AND "),binds:try key.map(bind))
                writeSQL=row.operation == "delete" ? plan.deleteSQL(predicate:lookup.sql) : plan.updateSQL(expressions:expressions.map(\.sql),predicate:lookup.sql)
                binds=expressions.flatMap(\.binds)+lookup.binds
            }
            body += try program.expand(writeSQL,binds)+";\n"
            let expected=row.operation == "update" && exactImage(row.before,row.after) ? 0 : 1
            body += "IF ROW_COUNT()!=\(expected) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='unexpected target affected-row count'; END IF;\n"
            if let after=row.after {
                let match=try predicate(after)
                body += "IF NOT EXISTS(SELECT 1 FROM \(try table.sqlName) WHERE \(try program.expand(match.sql,match.binds))) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='target after-image mismatch'; END IF;\n"
            }
            relaxed = relaxed || EnumZeroWrite.required(table:table,after:row.after)
        }
        let definition="CREATE FUNCTION \(MyISAMGTIDProgram.function)() RETURNS BIGINT DETERMINISTIC MODIFIES SQL DATA SQL SECURITY INVOKER COMMENT '\(MyISAMGTIDProgram.owner)' BEGIN\n"+body+"RETURN \(group.mutations.count); END"
        try require(definition.utf8.count+1 <= packetByteLimit,"MyISAM GTID group program exceeds target max_allowed_packet; increase the target setting")
        try withoutScratchLogging {
            try prepareGTIDScratch()
            // Keep binary float and unsigned parameters on the prepared protocol.
            for column in ["i","u","f","d","t","b","dt","tm","ts"] {
                let entries=program.values.enumerated().filter {$0.element.0 == column}
                for start in stride(from:0,to:entries.count,by:32) {
                    let chunk=entries[start..<min(start+32,entries.count)]
                    let sql="INSERT INTO \(MyISAMGTIDProgram.parameters) (`id`,`\(column)`) VALUES "+chunk.map {"(\($0.offset+1),?)"}.joined(separator:",")
                    _ = try query(sql,chunk.map {$0.element.1})
                }
            }
            // A stored routine retains its creation sql_mode. All relaxed writes
            // have an exact after-image check before the function can succeed.
            try EnumZeroWrite.withMode(required:relaxed,
                setMode:{_ = try self.query("SET SESSION sql_mode='\($0)'")},
                discardConnection:{try? self.connection.close().wait()}) {
                _ = try query(definition,textProtocol:true)
            }
        }
        let result=try sourceStatement(group.group.gtid!) {
            try query("SELECT \(MyISAMGTIDProgram.function)() AS applied",textProtocol:true,mutation:true).0
        }
        try require(result.first?.column("applied")?.int == group.mutations.count,"MyISAM GTID group did not complete")
        for mutation in group.mutations {
            if let after=mutation.row.after {try verifyGeneratedValues(mutation.table,after:after,plan:sqlPlan(mutation.table))}
        }
        try withoutScratchLogging {
            _ = try query("DROP FUNCTION \(MyISAMGTIDProgram.function)",textProtocol:true)
            _ = try query("TRUNCATE TABLE \(MyISAMGTIDProgram.parameters)",textProtocol:true)
        }
    }
}
