"""Generate the native identifier lowercase map from two MySQL source trees."""
import argparse
from pathlib import Path
import re


def read_map(path):
    text = path.read_text()
    pages = re.search(r'my_unicase_pages_default\[256\]\s*=\s*\{(.*?)\};', text, re.S)
    if not pages:
        raise ValueError(f'{path}: missing default case pages')
    names = re.findall(r'plane[0-9A-F]+|NULL|nullptr', pages[1])
    if len(names) != 256:
        raise ValueError(f'{path}: expected 256 case pages')
    result = {}
    for page, name in enumerate(names):
        if name in ('NULL', 'nullptr'):
            continue
        body = re.search(r'\b' + name + r'\[\]\s*=\s*\{(.*?)\};', text, re.S)
        if not body:
            raise ValueError(f'{path}: missing {name}')
        triples = re.findall(r'\{(0x[0-9A-Fa-f]+),\s*(0x[0-9A-Fa-f]+),\s*(0x[0-9A-Fa-f]+)\}', body[1])
        if len(triples) != 256:
            raise ValueError(f'{path}: expected 256 entries in {name}')
        for offset, (_, lower, _) in enumerate(triples):
            point = page * 256 + offset
            lower = int(lower, 16)
            if point != lower:
                result[point] = lower
    return result


def render(mapping):
    points = sorted(mapping)
    ranges = []
    while points:
        start = points.pop(0)
        delta = mapping[start] - start
        end = start
        step = points[0] - start if points else 1
        if step not in (1, 2):
            step = 1
        while points and points[0] == end + step and mapping[points[0]] - points[0] == delta:
            end = points.pop(0)
        ranges.append((start, end, step, delta))
    expanded = {point: point + delta for start, end, step, delta in ranges
                for point in range(start, end + 1, step)}
    if expanded != mapping:
        raise ValueError('range encoding changed the native map')
    body = '\n'.join(f'            (0x{a:04X},0x{b:04X},{s},{d}),' for a,b,s,d in ranges)
    return '''// Generated by tools/mysql_identifier_map.py. Do not edit this file by hand.
// Facts from my_unicase_pages_default in the pinned MySQL 5.7 and 8.4 trees.
// Both trees contain the same 696 non-identity lowercase mappings.
// See PLAN/IDENTIFIER_SUPPORT.md for source revisions and native probes.
enum NativeIdentifierLowercase {
    static let map: [UInt32:UInt32] = {
        let ranges: [(Int,Int,Int,Int)] = [
''' + body + '''
        ]
        var result: [UInt32:UInt32] = [:]
        result.reserveCapacity(696)
        for (first,last,step,delta) in ranges {
            for point in stride(from:first,through:last,by:step) {
                result[UInt32(point)]=UInt32(point+delta)
            }
        }
        return result
    }()
}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--mysql57', type=Path, required=True)
    parser.add_argument('--mysql84', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    mapping = read_map(args.mysql57 / 'strings/ctype-utf8.c')
    other = read_map(args.mysql84 / 'strings/ctype-utf8.cc')
    if mapping != other or len(mapping) != 696:
        parser.error('native identifier maps changed; inspect both versions before regeneration')
    output = render(mapping)
    if args.check:
        if args.output.read_text() != output:
            parser.error('generated identifier map differs')
    else:
        args.output.write_text(output)


if __name__ == '__main__':
    main()
